// Reproducible, small TF-IDF nearest-prototype intent classifier. No user data.
// This is a narrow navigation model, not a general language model.
import {writeFile} from 'node:fs/promises';
const corpus = {
  scene0: ['拍照解题','拍照','解题','打开拍照解题','进入拍照模式','切换到解题','我想拍一道题','我要拍题','我想用眼镜做题','帮我切到做题功能','我要使用解题功能','打开题目识别','选择学习解题','我想识别题目','看看这道题怎么做'],
  scene1: ['会议纪要','会议','打开会议纪要','切换到会议模式','我要记会议内容','我想记录会议','开始记笔记','我要做会议记录','帮我切到会议功能','打开会议助手','我想整理会议记录','选择会议录音','我要用会议纪要功能','打开开会记录'],
  scene2: ['实时翻译','翻译','打开实时翻译','进入翻译模式','切换到翻译功能','我想用翻译','帮我打开翻译功能','我要听外语翻译','我听不懂外语','打开语言翻译','选择翻译助手','我要进行实时翻译','我想使用翻译功能','外语听不懂'],
  scene3: ['地图','导航','打开地图','进入导航模式','切换到地图功能','我想用导航','帮我打开导航功能','我要看地图','我想看看怎么走','给我看看地图','选择地图导航','打开路线导航','我想找路','我要使用地图功能','我想看看路线'],
  previous: ['上一个','上一个功能','选择前一个','往前翻一项','向前切换','换到上一个功能','前一个选项'],
  next: ['下一个','下一个功能','选择后一个','往后翻一项','向后切换','换到下一个功能','后一个选项'],
  home: ['主菜单','返回主菜单','回到首页','返回功能列表','回到功能选择','打开功能菜单','返回菜单'],
  reject: ['今天的会议还没结束','会议内容很好','地图很好看','翻译不准确','这道题很难','我不需要地图','不要打开翻译','取消解题','不想开会','帮我播放音乐','今天天气怎么样','你是谁','打开浏览器','下一周开会','上一年做题','翻译是什么','导航好用吗','我想删除文件','给朋友发送邮件','谢谢','你好','我不想用导航','拍照和地图有什么区别','会议和翻译哪个好','实时翻译支持哪些语言','解题功能有什么用','我要买眼镜','未知功能']
};
const normalize = text => text.toLowerCase().replace(/[\s\p{P}]/gu, '');
const features = text => {
  const s = '^' + normalize(text) + '$', terms = new Set();
  for (const size of [2,3]) for (let i=0;i<=s.length-size;i++) terms.add(s.slice(i,i+size));
  return [...terms];
};
const examples = Object.entries(corpus).flatMap(([label, texts]) => texts.map(text => ({label, terms:features(text)})));
const df = {};
for (const {terms} of examples) for (const term of terms) df[term]=(df[term]||0)+1;
const idf = Object.fromEntries(Object.entries(df).map(([term,count]) => [term, +Math.log(1+examples.length/(1+count)).toFixed(5)]));
const samples = examples.map(({label,terms})=>{
  const length = Math.sqrt(terms.reduce((sum,term)=>sum+idf[term]**2,0));
  return {label, vector:Object.fromEntries(terms.map(term=>[term, +(idf[term]/length).toFixed(5)]))};
});
const model={version:'navigation-tfidf-1',algorithm:'character-2-3gram-tfidf-nearest-prototype',threshold:.52,margin:.12,idf,samples};
await writeFile(new URL('../../langgraph-app/lg_assistant/web/static/edge-intent-model.js',import.meta.url),`/* Generated by frontend/scripts/train-edge-intent.mjs; no user data. */\nwindow.EdgeIntentWeights = ${JSON.stringify(model)};\n`);
console.log(`Trained ${samples.length} navigation examples, ${Object.keys(idf).length} features.`);
